const { _electron: electron } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
(async () => {
  const packaged = process.argv.includes('--packaged');
  const app = await electron.launch({ executablePath: path.join(root, packaged ? 'dist/win-unpacked/KML Transit Journey.exe' : 'node_modules/electron/dist/electron.exe'), args: packaged ? ['--smoke-test'] : [root, '--smoke-test'], timeout: 30000 });
  const errors = [];
  try {
    const page = await app.firstWindow();
    page.setDefaultTimeout(15000);
    page.on('pageerror', e => errors.push(e.message));
    await page.waitForFunction(() => document.querySelector('#from').options.length > 10);
    const prefs = await app.evaluate(({BrowserWindow}) => BrowserWindow.getAllWindows()[0].webContents.getLastWebPreferences());
    assert.equal(prefs.nodeIntegration, false); assert.equal(prefs.contextIsolation, true); assert.equal(prefs.sandbox, true);
    await page.route('https://**', route => route.abort());
    await page.locator('#station-tab').click();
    await page.locator('#go').click();
    await page.locator('.journey-head').waitFor();
    assert((await page.locator('#results').innerText()).includes('transfer'));
    console.log('PASS: actual Electron launch, isolation, sample-network route');
    const wasDark = await page.locator('body').evaluate(el => el.classList.contains('dark'));
    await page.locator('#theme-toggle').click();
    assert.equal(await page.locator('body').evaluate(el => el.classList.contains('dark')), !wasDark);
    await page.locator('#operations-settings').click();
    const mode = page.locator('#service-list select').first();
    assert.equal(await mode.inputValue(), 'Metro');
    await mode.selectOption('Light rail (LRT)');
    assert.equal(await page.locator('#service-list input').first().inputValue(), '36');
    await page.locator('#service-reset').click();
    assert.equal(await page.locator('#service-list select').first().inputValue(), 'Metro');
    await page.locator('#service-close').click();
    console.log('PASS: theme, settings modal, manual mode presets, reset');
    const malicious = '<img src=x onerror="window.injected=true">';
    const kml = `<kml xmlns="http://www.opengis.net/kml/2.2"><Document><Placemark><name>Test Line</name><LineString><coordinates>0,0 0.01,0</coordinates></LineString></Placemark><Placemark><name><![CDATA[${malicious}]]></name><Point><coordinates>0,0</coordinates></Point></Placemark><Placemark><name>End</name><Point><coordinates>0.01,0</coordinates></Point></Placemark></Document></kml>`;
    await page.locator('#kml-upload').setInputFiles({name:'test.kml',mimeType:'application/vnd.google-earth.kml+xml',buffer:Buffer.from(kml)});
    await page.waitForFunction(() => document.querySelector('#from').options.length === 2);
    const metro = await page.evaluate(() => {from.value='0';to.value='1';return pathfind().duration});
    await page.locator('#operations-settings').click();
    await page.locator('#service-list select').first().selectOption('Light rail (LRT)');
    const lrt = await page.evaluate(() => {from.value='0';to.value='1';return pathfind().duration});
    assert(lrt > metro, `LRT ${lrt} must take longer than Metro ${metro}`);
    await page.locator('#service-close').click();
    await page.locator('#go').click();
    assert.equal(await page.locator('#results img').count(), 0);
    const tooltip = await page.evaluate(() => {const layer=stationLayers.getLayers().find(l=>l.getTooltip && l.getTooltip());return layer.getTooltip().getContent()});
    assert(!tooltip.includes('<img'), 'Imported names must be escaped in Leaflet tooltips');
    assert.equal(await page.evaluate(() => window.injected), undefined);
    console.log('PASS: real KML import, route recalculation, injected-name escaping');
    await page.locator('#kml-upload').setInputFiles({name:'bad.kml',mimeType:'application/xml',buffer:Buffer.from('<broken>')});
    await page.waitForFunction(() => document.querySelector('#import-status').textContent.includes('Import failed'));
    assert.equal(await page.locator('#from option').count(),2);
    console.log('PASS: invalid KML rejected without losing current network');
    await page.route('https://photon.komoot.io/**', route => {
      const q = new URL(route.request().url()).searchParams.get('q');
      const coord = q === 'Origin' ? [0,0] : [.01,0];
      return route.fulfill({json:{features:[{geometry:{coordinates:coord},properties:{name:q}}]}});
    });
    await page.locator('#address-tab').click();
    await page.locator('#address-from').fill('Origin');
    await page.locator('#suggest-from button').first().click();
    await page.locator('#address-to').fill('Destination');
    await page.locator('#suggest-to button').first().click();
    await page.locator('#address-go').click();
    await page.waitForFunction(() => document.querySelector('#address-status').textContent.startsWith('Route found'));
    assert((await page.locator('#results').innerText()).includes('approx.'));
    await page.locator('#swap-addresses').click();
    assert.equal(await page.locator('#address-from').inputValue(),'Destination');
    console.log('PASS: mocked geocoding, unavailable walking-service fallback, swap');
    assert.deepEqual(errors, []);
    console.log('PASS: no renderer exceptions captured');
  } finally { await app.close(); }
})().catch(e => { console.error(e); process.exitCode=1; });
